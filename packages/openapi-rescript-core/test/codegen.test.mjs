import {readFileSync, readdirSync} from "node:fs"
import {describe, expect, it} from "vitest"
import {generate} from "../lib/js/src/OpenapiGenerator.bs.js"

const normalizedPetstore = JSON.parse(
  readFileSync(new URL("./fixtures/petstore.normalized.json", import.meta.url), "utf8"),
)
const normalizedAuthenticatedApi = JSON.parse(
  readFileSync(new URL("./fixtures/authenticated-api.normalized.json", import.meta.url), "utf8"),
)
const normalizedEnums = JSON.parse(
  readFileSync(new URL("./fixtures/enums.normalized.json", import.meta.url), "utf8"),
)

const generateWithOptions = (input, options) => generate(input, options)
const sortFiles = files => [...files].sort((left, right) => left.path.localeCompare(right.path))

const readGoldenFiles = fixtureName => {
  let fixtureDir = new URL(`./golden/${fixtureName}/`, import.meta.url)

  return readdirSync(fixtureDir)
    .sort()
    .map(fileName => ({
      path: fileName,
      contents: readFileSync(new URL(`./golden/${fixtureName}/${fileName}`, import.meta.url), "utf8"),
    }))
}

const generatedFile = (output, path) => output.files.find(file => file.path === path)?.contents

describe("codegen", () => {
  it("emits the expected ReScript modules for the petstore fixture", () => {
    let output = generate(normalizedPetstore)

    expect(output.ok).toBe(true)
    expect(output.files).toEqual(readGoldenFiles("petstore"))
  })

  it("emits and exports one tag module for every declared or referenced tag", () => {
    let multiTagFixture = {
      openapi: "3.1.0",
      info: {
        title: "Tagged API",
        version: "1.0.0",
      },
      tags: [{name: "pets"}, {name: "featured"}, {name: "admin"}],
      paths: {
        "/pets": {
          get: {
            tags: ["pets", "featured"],
            operationId: "listPets",
            responses: {
              200: {
                description: "ok",
              },
            },
          },
        },
      },
    }

    let output = generate(multiTagFixture)

    expect(output.ok).toBe(true)
    expect(output.files.map(file => file.path)).toEqual([
      "Client.res",
      "Index.res",
      "Models.res",
      "Pets.res",
      "Featured.res",
      "Admin.res",
      "Schemas.res",
    ])
    expect(output.files.find(file => file.path === "Featured.res")?.contents).toContain(
      'name: "listPets"',
    )
    expect(output.files.find(file => file.path === "Admin.res")?.contents).toBe(
      "// Generated by openapi-rescript-core.\n\n",
    )
    expect(output.files.find(file => file.path === "Index.res")?.contents).toContain(
      "module Featured = Featured",
    )
    expect(output.files.find(file => file.path === "Index.res")?.contents).toContain(
      "module Admin = Admin",
    )
  })

  it("emits the expected ReScript modules for open and closed enum modes", () => {
    let openOutput = generateWithOptions(normalizedEnums, {enumMode: "open"})
    let closedOutput = generateWithOptions(normalizedEnums, {enumMode: "closed"})
    let openModels = generatedFile(openOutput, "Models.res")
    let closedModels = generatedFile(closedOutput, "Models.res")
    let openSchemas = generatedFile(openOutput, "Schemas.res")
    let closedSchemas = generatedFile(closedOutput, "Schemas.res")

    expect(openOutput.ok).toBe(true)
    expect(closedOutput.ok).toBe(true)
    expect(sortFiles(openOutput.files)).toEqual(readGoldenFiles("enums-open"))
    expect(sortFiles(closedOutput.files)).toEqual(readGoldenFiles("enums-closed"))
    expect(openModels).toContain("| Unknown(string)")
    expect(closedModels).not.toContain("| Unknown(string)")
    expect(openModels.indexOf("type sessionVisibility =")).toBeLessThan(
      openModels.indexOf("type session = {"),
    )
    expect(openModels).toContain("state: sessionState,")
    expect(openModels).toContain("visibility: sessionVisibility,")
    expect(closedModels).toContain("state: sessionState,")
    expect(closedModels).toContain("visibility: sessionVisibility,")
    expect(openSchemas.indexOf("let sessionVisibility: t<Models.sessionVisibility> = stringMapped(")).toBeLessThan(
      openSchemas.indexOf("let session: t<Models.session> = object_(["),
    )
    expect(closedSchemas.indexOf("let sessionVisibility: t<Models.sessionVisibility> = stringMapped(")).toBeLessThan(
      closedSchemas.indexOf("let session: t<Models.session> = object_(["),
    )
    expect(openSchemas).not.toContain("let sessionVisibility: t<Models.sessionVisibility> = string\n")
    expect(closedSchemas).not.toContain("let sessionVisibility: t<Models.sessionVisibility> = string\n")
  })

  it("rejects open enums when a declared value normalizes to the reserved Unknown constructor", () => {
    let reservedUnknownEnum = {
      openapi: "3.1.0",
      info: {
        title: "Reserved Unknown Enum API",
        version: "1.0.0",
      },
      components: {
        schemas: {
          Status: {
            type: "string",
            enum: ["unknown", "ready"],
          },
        },
      },
      paths: {},
    }

    expect(generateWithOptions(reservedUnknownEnum, {enumMode: "open"})).toMatchObject({
      ok: false,
      error: {
        path: ["components", "schemas", "Status", "enum", "0"],
        message: "Enum constructor collision with reserved open enum constructor: Unknown",
      },
    })
    expect(generateWithOptions(reservedUnknownEnum, {enumMode: "closed"})).toMatchObject({
      ok: true,
    })
  })

  it("preserves schema-less responses as None in emitted metadata", () => {
    let noBodyResponseFixture = {
      openapi: "3.1.0",
      info: {
        title: "No Body API",
        version: "1.0.0",
      },
      paths: {
        "/pets/{petId}": {
          delete: {
            operationId: "deletePet",
            tags: ["pets"],
            parameters: [
              {
                name: "petId",
                in: "path",
                required: true,
                schema: {
                  type: "string",
                },
              },
            ],
            responses: {
              204: {
                description: "deleted",
              },
            },
          },
        },
      },
    }

    let output = generate(noBodyResponseFixture)

    expect(output.ok).toBe(true)
    expect(output.files.find(file => file.path === "Pets.res")?.contents).toContain("schema: None,")
    expect(output.files.find(file => file.path === "Pets.res")?.contents).not.toContain(
      'schema: Some("unit")',
    )
  })

  it("uses the default response schema as the generated result type when no explicit 2xx schema exists", () => {
    let defaultResponseFixture = {
      openapi: "3.1.0",
      info: {
        title: "Default Success API",
        version: "1.0.0",
      },
      components: {
        schemas: {
          FallbackPayload: {
            type: "object",
            required: ["ok"],
            properties: {
              ok: {type: "boolean"},
            },
          },
        },
      },
      paths: {
        "/fallback": {
          get: {
            operationId: "fallbackSuccess",
            tags: ["default-success"],
            responses: {
              default: {
                description: "fallback success payload",
                content: {
                  "application/json": {
                    schema: {$ref: "#/components/schemas/FallbackPayload"},
                  },
                },
              },
            },
          },
        },
      },
    }

    let output = generate(defaultResponseFixture)
    let defaultSuccessModule = output.files.find(file => file.path === "DefaultSuccess.res")?.contents

    expect(output.ok).toBe(true)
    expect(defaultSuccessModule).toContain(
      "): promise<result<Models.fallbackPayload, Client.operationError>> =>",
    )
    expect(defaultSuccessModule).toContain('statusCode: "default"')
    expect(defaultSuccessModule).toContain(
      "schema: Some(OpenapiRescriptRuntime.Schema.toAny(Schemas.fallbackPayload))",
    )
  })

  it("keeps the explicit 2xx response schema as the generated result type when default is also present", () => {
    let mixedSuccessFixture = {
      openapi: "3.1.0",
      info: {
        title: "Mixed Success API",
        version: "1.0.0",
      },
      components: {
        schemas: {
          ExplicitPayload: {
            type: "object",
            required: ["ok"],
            properties: {
              ok: {type: "boolean"},
            },
          },
          DefaultPayload: {
            type: "object",
            required: ["fallback"],
            properties: {
              fallback: {type: "boolean"},
            },
          },
        },
      },
      paths: {
        "/mixed": {
          get: {
            operationId: "mixedSuccesses",
            tags: ["mixed-success"],
            responses: {
              200: {
                description: "explicit success payload",
                content: {
                  "application/json": {
                    schema: {$ref: "#/components/schemas/ExplicitPayload"},
                  },
                },
              },
              default: {
                description: "default payload",
                content: {
                  "application/json": {
                    schema: {$ref: "#/components/schemas/DefaultPayload"},
                  },
                },
              },
            },
          },
        },
      },
    }

    let output = generate(mixedSuccessFixture)
    let mixedSuccessModule = output.files.find(file => file.path === "MixedSuccess.res")?.contents

    expect(output.ok).toBe(true)
    expect(mixedSuccessModule).toContain(
      "): promise<result<Models.explicitPayload, Client.operationError>> =>",
    )
    expect(mixedSuccessModule).toContain('statusCode: "200"')
    expect(mixedSuccessModule).toContain('statusCode: "default"')
  })

  it("assigns unique module and file names when distinct tags sanitize to the same identifier", () => {
    let collidingTagsFixture = {
      openapi: "3.1.0",
      info: {
        title: "Colliding Tags API",
        version: "1.0.0",
      },
      tags: [{name: "pet-store"}, {name: "pet store"}],
      paths: {
        "/pets": {
          get: {
            operationId: "listPets",
            tags: ["pet-store"],
            responses: {
              200: {
                description: "ok",
              },
            },
          },
          post: {
            operationId: "createPet",
            tags: ["pet store"],
            responses: {
              201: {
                description: "created",
              },
            },
          },
        },
      },
    }

    let output = generate(collidingTagsFixture)

    expect(output.ok).toBe(true)
    expect(output.files.map(file => file.path)).toEqual([
      "Client.res",
      "Index.res",
      "Models.res",
      "PetStore.res",
      "PetStore2.res",
      "Schemas.res",
    ])
    expect(output.files.find(file => file.path === "PetStore.res")?.contents).toContain(
      'name: "listPets"',
    )
    expect(output.files.find(file => file.path === "PetStore2.res")?.contents).toContain(
      'name: "createPet"',
    )
    expect(output.files.find(file => file.path === "Index.res")?.contents).toContain(
      "module PetStore = PetStore",
    )
    expect(output.files.find(file => file.path === "Index.res")?.contents).toContain(
      "module PetStore2 = PetStore2",
    )
  })

  it("emits security scheme metadata into generated operations", () => {
    let output = generate(normalizedAuthenticatedApi)
    let defaultModule = output.files.find(file => file.path === "Default_.res")?.contents

    expect(output.ok).toBe(true)
    expect(defaultModule).toContain("securitySchemes: [")
    expect(defaultModule).toContain('name: "ApiKeyHeader"')
    expect(defaultModule).toContain('credentialName: Some("X-API-Key")')
    expect(defaultModule).toContain('name: "BearerAuth"')
    expect(defaultModule).toContain('authKind: "httpBearer"')
    expect(defaultModule).toContain('name: "BasicAuth"')
    expect(defaultModule).toContain('authKind: "httpBasic"')
  })

  it("keeps explicit operation-level security clears in emitted operations", () => {
    let explicitSecurityClear = {
      ...normalizedAuthenticatedApi,
      paths: {
        ...normalizedAuthenticatedApi.paths,
        "/profile": {
          ...normalizedAuthenticatedApi.paths["/profile"],
          get: {
            ...normalizedAuthenticatedApi.paths["/profile"].get,
            security: [],
          },
        },
      },
    }

    let output = generate(explicitSecurityClear)
    let defaultModule = output.files.find(file => file.path === "Default_.res")?.contents

    expect(output.ok).toBe(true)
    expect(defaultModule).toContain("security: [],")
  })

  it("emits compilable quoted record labels when parameter or schema field names are not plain identifiers", () => {
    let quotedFieldFixture = {
      openapi: "3.1.0",
      info: {
        title: "Quoted Fields API",
        version: "1.0.0",
      },
      tags: [{name: "unsafe"}],
      components: {
        schemas: {
          UserProfile: {
            type: "object",
            required: ["user-id", "type", "active"],
            properties: {
              "user-id": {type: "string"},
              type: {type: "string"},
              active: {type: "boolean"},
            },
          },
        },
      },
      paths: {
        "/users/{user-id}": {
          get: {
            operationId: "getUser",
            tags: ["unsafe"],
            parameters: [
              {
                name: "user-id",
                in: "path",
                required: true,
                schema: {type: "string"},
              },
              {
                name: "verbose",
                in: "query",
                required: false,
                schema: {type: "boolean"},
              },
            ],
            responses: {
              200: {
                description: "ok",
                content: {
                  "application/json": {
                    schema: {$ref: "#/components/schemas/UserProfile"},
                  },
                },
              },
            },
          },
        },
      },
    }

    let output = generate(quotedFieldFixture)
    let unsafeModule = output.files.find(file => file.path === "Unsafe.res")?.contents
    let modelsModule = output.files.find(file => file.path === "Models.res")?.contents

    expect(output.ok).toBe(true)
    expect(unsafeModule).toContain('"user-id": string,')
    expect(unsafeModule).toContain('"verbose": option<bool>,')
    expect(modelsModule).toContain('"user-id": string,')
    expect(modelsModule).toContain('"type": string,')
    expect(modelsModule).toContain('"active": bool,')
  })
})
